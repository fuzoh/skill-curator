//! `ATTRIBUTION.md` generation from `lock.toml` provenance.

use std::error::Error;
use std::fs;
use std::os::unix::fs::{PermissionsExt as _, symlink};

use skill_curator::collection::attribution::{self, ATTRIBUTION_FILE};
use skill_curator::collection::lock::Lock;
use tempfile::TempDir;

type TestResult = Result<(), Box<dyn Error>>;

const SHA1: &str = "0123456789abcdef0123456789abcdef01234567";
const SHA2: &str = "89abcdef0123456789abcdef0123456789abcdef";

/// A lock with a Copy Skill, an Adapt Skill without license, a Composition
/// of two Sources, and a local Skill.
fn lock_text() -> String {
    let hash = |fill: char| format!("sha256:{}", fill.to_string().repeat(64));
    format!(
        r#"format = 1

[skills.grill-me]
output_hash = "{a}"
inputs_hash = "{b}"

[[skills.grill-me.provenance]]
source = "mattpocock"
url = "https://github.com/mattpocock/skills.git"
upstream_path = "skills/grill-me"
revision = "{SHA1}"
licenses = [{{ path = "LICENSE", summary = "MIT" }}]

[skills.grilling]
output_hash = "{a}"
inputs_hash = "{b}"

[[skills.grilling.provenance]]
source = "unlicensed"
url = "https://example.com/skills.git"
upstream_path = "grilling"
revision = "{SHA2}"

[skills.code-review]
output_hash = "{a}"
inputs_hash = "{b}"

[[skills.code-review.provenance]]
input = "review"
source = "mattpocock"
url = "https://github.com/mattpocock/skills.git"
upstream_path = "skills/review"
revision = "{SHA1}"
licenses = [{{ path = "LICENSE", summary = "MIT" }}]

[[skills.code-review.provenance]]
input = "critique"
source = "pstack"
url = "https://github.com/cursor/plugins.git"
upstream_path = "pstack/critique"
revision = "{SHA2}"
licenses = [{{ path = "LICENSE" }}, {{ path = "pstack/LICENSE", summary = "Apache-2.0" }}]

[skills.fr-learner-voice]
output_hash = "{a}"
"#,
        a = hash('a'),
        b = hash('b'),
    )
}

const EXPECTED: &str = "# Attribution

<!-- Generated by skill-curator from lock.toml. Do not edit: changes are overwritten. -->

Skills in this Collection derived from upstream Sources, with the Revision each was taken from and the license files found for it. Each license applies to the content it accompanies upstream.

## `code-review`

Composition of 2 upstream Skills.

- Input `critique`: `pstack/critique` from Source `pstack` (`https://github.com/cursor/plugins.git`) at Revision `89abcdef0123456789abcdef0123456789abcdef`
  - License: `LICENSE` (unidentified)
  - License: `pstack/LICENSE` (`Apache-2.0`)
- Input `review`: `skills/review` from Source `mattpocock` (`https://github.com/mattpocock/skills.git`) at Revision `0123456789abcdef0123456789abcdef01234567`
  - License: `LICENSE` (`MIT`)

## `grill-me`

- `skills/grill-me` from Source `mattpocock` (`https://github.com/mattpocock/skills.git`) at Revision `0123456789abcdef0123456789abcdef01234567`
  - License: `LICENSE` (`MIT`)

## `grilling`

- `grilling` from Source `unlicensed` (`https://example.com/skills.git`) at Revision `89abcdef0123456789abcdef0123456789abcdef`
  - License: none found; check the Source's terms before redistributing this Skill
";

#[test]
fn renders_single_source_skills_and_compositions() -> TestResult {
    let lock = Lock::from_toml(&lock_text())?;
    assert_eq!(attribution::render(&lock), EXPECTED);
    Ok(())
}

#[test]
fn rendering_ignores_the_order_of_provenance_entries() -> TestResult {
    let mut lock = Lock::from_toml(&lock_text())?;
    for skill in lock.skills.values_mut() {
        skill.provenance.reverse();
    }
    assert_eq!(attribution::render(&lock), EXPECTED);
    Ok(())
}

#[test]
fn writes_the_file_at_the_collection_root() -> TestResult {
    let dir = TempDir::new()?;
    let lock = Lock::from_toml(&lock_text())?;
    attribution::write(dir.path(), &lock)?;
    let path = dir.path().join(ATTRIBUTION_FILE);
    assert_eq!(fs::read_to_string(&path)?, EXPECTED);
    assert_eq!(fs::metadata(&path)?.permissions().mode() & 0o777, 0o644);

    // Writing again yields the same bytes.
    attribution::write(dir.path(), &lock)?;
    assert_eq!(fs::read_to_string(&path)?, EXPECTED);
    assert_eq!(
        fs::read_dir(dir.path())?.count(),
        1,
        "no temporary file is left"
    );
    Ok(())
}

#[test]
fn a_symbolic_link_at_the_attribution_path_is_replaced_not_followed() -> TestResult {
    let dir = TempDir::new()?;
    let outside = TempDir::new()?;
    let target = outside.path().join("victim.md");
    fs::write(&target, "untouched\n")?;
    symlink(&target, dir.path().join(ATTRIBUTION_FILE))?;

    attribution::write(dir.path(), &Lock::from_toml(&lock_text())?)?;
    assert_eq!(fs::read_to_string(&target)?, "untouched\n");
    let path = dir.path().join(ATTRIBUTION_FILE);
    assert!(!fs::symlink_metadata(&path)?.file_type().is_symlink());
    assert_eq!(fs::read_to_string(path)?, EXPECTED);
    Ok(())
}
