//! `ATTRIBUTION.md`: provenance and license notices for every upstream Skill
//! of the Collection, generated from `lock.toml`.
//!
//! The text depends only on the lock's content: Skills are listed by name and
//! provenance entries by Composition input, Source, and path, whatever order
//! `lock.toml` stores them in.

use std::fmt::Write as _;
use std::fs::Permissions;
use std::io::Write as _;
use std::os::unix::fs::PermissionsExt as _;
use std::path::Path;

use super::CollectionError;
use super::lock::{Lock, Provenance};

/// Attribution file name at the Collection root.
pub const ATTRIBUTION_FILE: &str = "ATTRIBUTION.md";

/// Renders `ATTRIBUTION.md` for `lock`.
#[must_use]
pub fn render(lock: &Lock) -> String {
    let mut text = String::from(
        "# Attribution\n\n<!-- Generated by skill-curator from lock.toml. Do not edit: changes are overwritten. -->\n\n",
    );
    let upstream = lock
        .skills
        .iter()
        .filter(|(_, skill)| !skill.provenance.is_empty())
        .collect::<Vec<_>>();
    if upstream.is_empty() {
        text.push_str("This Collection holds no Skills from upstream Sources.\n");
        return text;
    }
    text.push_str(
        "Skills in this Collection derived from upstream Sources, with the Revision each was taken from and the license files found for it. Each license applies to the content it accompanies upstream.\n",
    );
    for (name, skill) in upstream {
        let mut entries = skill.provenance.iter().collect::<Vec<_>>();
        entries.sort_by(|a, b| {
            (&a.input, &a.source, &a.upstream_path).cmp(&(&b.input, &b.source, &b.upstream_path))
        });
        let _ = write!(text, "\n## {}\n\n", code(name.as_str()));
        if entries.iter().any(|entry| entry.input.is_some()) {
            let _ = writeln!(text, "Composition of {} upstream Skills.\n", entries.len());
        }
        for entry in entries {
            render_entry(&mut text, entry);
        }
    }
    text
}

fn render_entry(text: &mut String, entry: &Provenance) {
    text.push_str("- ");
    if let Some(input) = &entry.input {
        let _ = write!(text, "Input {}: ", code(input.as_str()));
    }
    let _ = writeln!(
        text,
        "{} from Source {} ({}) at Revision {}",
        code(entry.upstream_path.as_str()),
        code(entry.source.as_str()),
        code(&entry.url),
        code(entry.revision.as_str()),
    );
    if entry.licenses.is_empty() {
        text.push_str(
            "  - License: none found; check the Source's terms before redistributing this Skill\n",
        );
    }
    for license in &entry.licenses {
        let summary = license
            .summary
            .as_deref()
            .map_or_else(|| "unidentified".to_owned(), code);
        let _ = writeln!(
            text,
            "  - License: {} ({summary})",
            code(license.path.as_str())
        );
    }
}

/// Markdown inline code for `value`, fenced with more backticks than any run
/// inside it and with newlines flattened, so no lock value can break out.
fn code(value: &str) -> String {
    let value = value.replace(['\r', '\n'], " ");
    let longest = value.split(|c| c != '`').map(str::len).max().unwrap_or(0);
    let fence = "`".repeat(longest + 1);
    if longest == 0 {
        format!("{fence}{value}{fence}")
    } else {
        format!("{fence} {value} {fence}")
    }
}

/// Writes `ATTRIBUTION.md` for `lock` at the Collection `root`.
///
/// The file is written to a temporary file and renamed into place, so a
/// failure never leaves it half-written, and a symbolic link at its path is
/// replaced rather than followed.
///
/// # Errors
///
/// Returns [`CollectionError::Write`] when the file cannot be written.
pub fn write(root: &Path, lock: &Lock) -> Result<(), CollectionError> {
    let path = root.join(ATTRIBUTION_FILE);
    let write_error = |source| CollectionError::Write {
        path: path.clone(),
        source,
    };
    let mut file = tempfile::NamedTempFile::new_in(root).map_err(write_error)?;
    file.write_all(render(lock).as_bytes())
        .map_err(write_error)?;
    // Temporary files are private; the notice is an ordinary Collection file.
    file.as_file()
        .set_permissions(Permissions::from_mode(0o644))
        .map_err(write_error)?;
    file.persist(&path).map_err(|err| write_error(err.error))?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn code_spans_cannot_be_broken_out_of() {
        assert_eq!(code("skills/a"), "`skills/a`");
        assert_eq!(code("a`b"), "`` a`b ``");
        assert_eq!(code("a``b`"), "``` a``b` ```");
        assert_eq!(code("line\nbreak"), "`line break`");
        assert_eq!(code(""), "``");
    }

    #[test]
    fn an_empty_lock_says_so() {
        let text = render(&Lock::default());
        assert!(text.starts_with("# Attribution\n"));
        assert!(text.ends_with("This Collection holds no Skills from upstream Sources.\n"));
    }
}
